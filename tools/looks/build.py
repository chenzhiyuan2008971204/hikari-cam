"""Bake every look in presets.py into a .cube LUT, generate the Kotlin preset list, and render
preview sheets so each look can be checked by eye.

  python3 build.py                      bake LUTs + Kotlin + previews of all looks
  python3 build.py --only hamada,leiter previews for some looks (still bakes all)
  python3 build.py --photos DIR         use your own test photos for previews (default: ./photos)
"""
import argparse
import glob
import os

import numpy as np
from PIL import Image, ImageDraw, ImageFont

import look as engine
from presets import LOOKS as _BASE, SHIP

HERE_ = os.path.dirname(os.path.abspath(__file__))


def load_looks():
    """presets.py, with any fitted/<key>.json (written by fit.py) replacing the hand-tuned look."""
    import json
    looks = dict(_BASE)
    for f in sorted(glob.glob(os.path.join(HERE_, "fitted", "*.json"))):
        k = os.path.splitext(os.path.basename(f))[0]
        if k in looks:
            with open(f) as fh:
                looks[k] = json.load(fh)
    return looks


LOOKS = load_looks()

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ASSETS = os.path.join(ROOT, "app/src/main/assets/looks")
KOTLIN = os.path.join(ROOT, "app/src/main/java/com/hikari/cam/filter/StylePresets.kt")
XMP_DIR = os.path.join(ROOT, "app/src/main/assets/xmp")
COMPARE_DIR = os.path.join(ROOT, "app/src/main/assets/compare")
SIZE = 33


def bake(look, n=SIZE):
    g = np.linspace(0, 1, n)
    # .cube order: red changes fastest
    b, gg, r = np.meshgrid(g, g, g, indexing="ij")
    grid = np.stack([r, gg, b], -1).reshape(-1, 3)
    return engine.apply(look, grid).reshape(n, n, n, 3)  # [b][g][r]


def write_cube(path, table, title):
    n = table.shape[0]
    with open(path, "w") as f:
        f.write(f'TITLE "{title}"\nLUT_3D_SIZE {n}\n')
        for v in table.reshape(-1, 3):
            f.write(f"{v[0]:.4f} {v[1]:.4f} {v[2]:.4f}\n")


def apply_lut(table, img):
    """Trilinear lookup, same as the GPU does."""
    n = table.shape[0]
    p = np.clip(img, 0, 1) * (n - 1)
    i0 = np.clip(np.floor(p).astype(int), 0, n - 2)
    f = p - i0
    r0, g0, b0 = i0[..., 0], i0[..., 1], i0[..., 2]
    fr, fg, fb = f[..., 0:1], f[..., 1:2], f[..., 2:3]
    out = 0
    for db in (0, 1):
        for dg in (0, 1):
            for dr in (0, 1):
                w = (fr if dr else 1 - fr) * (fg if dg else 1 - fg) * (fb if db else 1 - fb)
                out = out + w * table[b0 + db, g0 + dg, r0 + dr]
    return out


def fx(img, look, seed=1):
    """Rough preview of the shader's spatial effects (vignette, grain, bloom)."""
    e = look.get("fx", {})
    h, w, _ = img.shape
    out = img.copy()
    if e.get("bloom") or e.get("halation"):
        from PIL import ImageFilter
        bright = np.clip((img - 0.6) / 0.4, 0, 1)
        blur = np.asarray(Image.fromarray((bright * 255).astype(np.uint8)).filter(
            ImageFilter.GaussianBlur(max(h, w) * 0.015)), float) / 255
        out = out + e.get("bloom", 0) * blur * 0.6
        out = out + e.get("halation", 0) * (blur @ engine.LUMA)[..., None] * np.array([1, .28, .12])
    if e.get("vignette"):
        y, x = np.mgrid[0:h, 0:w]
        ar = h / w
        d = np.hypot((x / w - .5), (y / h - .5) * ar) / np.hypot(.5, .5 * ar)
        t = np.clip((d - .35) / .65, 0, 1)
        out = out * (1 - e["vignette"] * .85 * (t * t * (3 - 2 * t)))[..., None]
    if e.get("grain"):
        rng = np.random.default_rng(seed)
        g = rng.standard_normal((h, w)) * 0.29
        L = out @ engine.LUMA
        out = out + (g * e["grain"] * 0.25 * (1 - 0.6 * np.abs(L * 2 - 1)))[..., None]
    return np.clip(out, 0, 1)


def swatch(lk):
    """Two chip colours: the look applied to a sky blue and to a warm skin tone."""
    import numpy as np
    return engine.apply(lk, np.array([[0.45, 0.62, 0.80], [0.85, 0.62, 0.50]]))


def kotlin(looks):
    lines = [
        "package com.hikari.cam.filter",
        "",
        "// Generated by tools/looks/build.py from tools/looks/presets.py. Do not edit by hand.",
        "",
        "/** Photographer-inspired looks: a baked 3D LUT for colour plus the shader's spatial effects. */",
        "object StylePresets {",
        "    val all: List<Filter> = listOf(",
    ]
    for k, lk in looks.items():
        if k not in SHIP:
            continue
        e = lk.get("fx", {})
        sw = ", ".join("0xFF%02X%02X%02XL" % tuple(int(v * 255 + .5) for v in c) for c in swatch(lk))
        args = ["lutAmount = 1f"] + [f"{p} = {e[p]}f" for p in
                                     ("grain", "vignette", "halation", "bloom", "leak") if e.get(p)]
        lines.append(
            f'        Filter("style_{k}", "{lk["name"]}", "{lk["subtitle"]}", Category.{lk["category"]},\n'
            f'            FilterParams({", ".join(args)}), lutFile = "asset:looks/{k}.cube",\n'
            f'            swatch = listOf({sw}), styleKey = "{k}",\n'
            f'            note = "{SHIP[k]}"),')
    lines += ["    )", "}", ""]
    return "\n".join(lines)


def write_compares(photo_dir, width=1080):
    """Before/after image per shipped look: top row original, bottom row with the look.
    Uses freely usable test photos (Kodak suite), never the photographers' own work."""
    os.makedirs(COMPARE_DIR, exist_ok=True)
    files = sorted(glob.glob(os.path.join(photo_dir, "*")))[:3]
    gap = 6
    h = (width - gap * (len(files) - 1)) // len(files)
    tiles = []
    for f in files:
        im = Image.open(f).convert("RGB")
        s = min(im.size)  # centre square crop
        im = im.crop(((im.width - s) // 2, (im.height - s) // 2, (im.width + s) // 2, (im.height + s) // 2))
        tiles.append(np.asarray(im.resize((h, h), Image.LANCZOS), float) / 255)
    for k in SHIP:
        t = bake(LOOKS[k])
        sheet = Image.new("RGB", (width, 2 * h + gap), (0, 0, 0))
        for i, a in enumerate(tiles):
            x = i * (h + gap)
            sheet.paste(Image.fromarray((a * 255 + .5).astype(np.uint8)), (x, 0))
            sheet.paste(Image.fromarray((apply_lut(t, a) * 255 + .5).astype(np.uint8)), (x, h + gap))
        sheet.save(os.path.join(COMPARE_DIR, k + ".jpg"), quality=88)


def font(sz):
    for p in ("/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
              "/usr/share/fonts/truetype/noto/NotoSansCJK-Regular.ttc",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"):
        if os.path.exists(p):
            return ImageFont.truetype(p, sz)
    return ImageFont.load_default()


def load_photos(d, tile):
    ims = []
    for f in sorted(glob.glob(os.path.join(d, "*"))):
        try:
            im = Image.open(f).convert("RGB")
        except Exception:
            continue
        im.thumbnail((tile, tile))
        ims.append(np.asarray(im, float) / 255)
    return ims


def sheet(rows, tile, out):
    """rows: list of (label, [images])."""
    lab = 150
    H = sum(max(i.shape[0] for i in r[1]) + 4 for r in rows)
    W = lab + sum(i.shape[1] + 4 for i in rows[0][1])
    s = Image.new("RGB", (W, H), (24, 24, 24))
    d = ImageDraw.Draw(s)
    f = font(16)
    y = 0
    for label, ims in rows:
        d.text((6, y + 6), label, fill=(235, 235, 235), font=f)
        x = lab
        for im in ims:
            s.paste(Image.fromarray((im * 255 + .5).astype(np.uint8)), (x, y))
            x += im.shape[1] + 4
        y += max(i.shape[0] for i in ims) + 4
    s.save(out, quality=92)


# Clean picture limits every look must pass (see presets.py).
CLEAN_LIMITS = dict(
    white_chroma=2.0,     # OKLab chroma x100 of pure white after the look (0 = neutral)
    lightgray_chroma=3.0, # same for a 92% grey (paper, clouds)
    white_level=0.95,     # darkest channel of pure white
    black_level=0.045,    # brightest channel of pure black (matte lift)
    skin_hue=12.0,        # max hue shift (deg) of skin tones
    skin_chroma=(0.65, 1.7),  # allowed chroma ratio of skin tones (below ~0.65 faces look grey)
    shadow_detail=0.06,   # luminance a 20% grey must keep (crushed shadows lose dark detail)
    highlight_sep=0.06,   # luminance gap kept between 80% and 95% grey (highlight detail)
)
# the furthest a look may widen CLEAN_LIMITS with its "allow" entry (film character, still clean)
FILM_ALLOWANCE = dict(
    white_chroma=4.0, lightgray_chroma=5.0, white_level=0.92, black_level=0.075,
    skin_hue=12.0, skin_chroma=(0.6, 1.7), shadow_detail=0.06, highlight_sep=0.05,
)
SKINS = {  # ColorChecker light / dark skin and a light East Asian skin tone
    "light": (194, 150, 130), "dark": (115, 82, 68), "asian": (226, 186, 160)}


def _lab(c):
    from colorlib import linear_to_oklab, srgb_to_linear
    import numpy as np
    return linear_to_oklab(srgb_to_linear(np.asarray(c, float)))


def clean_check(lk):
    """(list of failed checks, measured values) for one look against CLEAN_LIMITS."""
    import numpy as np
    # a look may widen individual limits on purpose (a faded film's lifted black, cream whites),
    # within FILM_ALLOWANCE: nothing beyond those bounds is ever accepted
    lim = dict(CLEAN_LIMITS)
    for key, v in lk.get("allow", {}).items():
        bound = FILM_ALLOWANCE[key]
        lim[key] = (max(v[0], bound[0]), min(v[1], bound[1])) if isinstance(v, tuple) else \
            (max(v, bound) if key in ("white_level", "shadow_detail", "highlight_sep") else min(v, bound))
    out = engine.apply(lk, np.array([[1, 1, 1], [.92, .92, .92], [0, 0, 0]]
                                    + [np.array(v) / 255 for v in SKINS.values()]))
    lw, lg = _lab(out[0]), _lab(out[1])
    tones = engine.apply(lk, np.array([[.2, .2, .2], [.8, .8, .8], [.95, .95, .95]])) @ engine.LUMA
    m = dict(white=np.hypot(*lw[1:]) * 100, grey92=np.hypot(*lg[1:]) * 100,
             whiteLv=out[0].min(), blackLv=out[2].max(), skinHue=None, skinC=None,
             shadow=tones[0], hlsep=tones[2] - tones[1])
    if lk.get("mono") is None:
        dh, cr = [], []
        for i, v in enumerate(SKINS.values()):
            a0, a1 = _lab(np.array(v) / 255), _lab(out[3 + i])
            h0, h1 = np.degrees(np.arctan2(a0[2], a0[1])), np.degrees(np.arctan2(a1[2], a1[1]))
            dh.append(abs((h1 - h0 + 180) % 360 - 180))
            cr.append(np.hypot(*a1[1:]) / np.hypot(*a0[1:]))
        m["skinHue"], m["skinC"] = max(dh), (min(cr), max(cr))
    fails = []
    if m["white"] > lim["white_chroma"]: fails.append("white")
    if m["grey92"] > lim["lightgray_chroma"]: fails.append("grey92")
    if m["whiteLv"] < lim["white_level"]: fails.append("whiteLv")
    if m["blackLv"] > lim["black_level"]: fails.append("blackLv")
    if m["skinHue"] is not None and m["skinHue"] > lim["skin_hue"]: fails.append("skinHue")
    if m["skinC"] is not None and not (lim["skin_chroma"][0] <= m["skinC"][0] and m["skinC"][1] <= lim["skin_chroma"][1]):
        fails.append("skinC")
    if m["shadow"] < lim["shadow_detail"]: fails.append("shadowDetail")
    if m["hlsep"] < lim["highlight_sep"]: fails.append("hlDetail")
    if any(v for v in lk.get("fx", {}).values()): fails.append("fx")
    return fails, m


def clean_report(looks, quiet=False):
    say = (lambda *x: None) if quiet else print
    say(f"{'look':<12}{'white':>7}{'grey92':>8}{'whiteLv':>9}{'blackLv':>9}{'skinHue':>9}{'skinC':>11}"
        f"{'shadow':>8}{'hlSep':>7}")
    bad = []
    for k, lk in looks.items():
        fails, m = clean_check(lk)
        sk = (f"{m['skinHue']:9.1f}{m['skinC'][0]:6.2f}-{m['skinC'][1]:.2f}" if m["skinHue"] is not None
              else f"{'-':>9}{'-':>11}")
        say(f"{k:<12}{m['white']:7.1f}{m['grey92']:8.1f}{m['whiteLv']:9.2f}{m['blackLv']:9.3f}{sk}"
            f"{m['shadow']:8.3f}{m['hlsep']:7.3f}"
            + ("   FAIL " + ",".join(fails) if fails else ""))
        if fails:
            bad.append(k)
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--only")
    ap.add_argument("--photos", default=os.path.join(HERE, "photos"))
    ap.add_argument("--out", default=os.path.join(HERE, "preview"))
    ap.add_argument("--tile", type=int, default=230)
    ap.add_argument("--no-bake", action="store_true")
    ap.add_argument("--compare", help="test photo folder for the in-app before/after images")
    a = ap.parse_args()

    keys = a.only.split(",") if a.only else list(LOOKS)
    bad = clean_report(LOOKS)
    if bad:
        raise SystemExit(f"not clean: {', '.join(bad)} (see CLEAN_LIMITS)")
    if not a.no_bake:
        import xmp
        os.makedirs(ASSETS, exist_ok=True)
        os.makedirs(XMP_DIR, exist_ok=True)
        for f in glob.glob(os.path.join(ASSETS, "*.cube")) + glob.glob(os.path.join(XMP_DIR, "*.xmp")):
            os.remove(f)  # only shipped looks stay bundled
        for k in SHIP:
            lk = LOOKS[k]
            write_cube(os.path.join(ASSETS, k + ".cube"), bake(lk), lk["subtitle"])
            table = xmp.bake_rgb_slowest(lambda c, lk=lk: engine.apply(lk, c))
            with open(os.path.join(XMP_DIR, k + ".xmp"), "w") as f:
                f.write(xmp.profile_xmp(table, f'Hikari {lk["subtitle"]}', "Hikari 光",
                                        f'{lk["name"]} 風格（Hikari 相機）'))
        if a.compare:
            write_compares(a.compare)
        with open(KOTLIN, "w") as f:
            f.write(kotlin(LOOKS))

    photos = load_photos(a.photos, a.tile)
    if not photos:
        print("no photos in", a.photos, "- skipping previews")
        return
    os.makedirs(a.out, exist_ok=True)
    rows = [("original", photos)]
    for k in keys:
        lk = LOOKS[k]
        t = bake(lk)
        rows.append((f'{k}\n{lk["subtitle"]}', [fx(apply_lut(t, p), lk, i) for i, p in enumerate(photos)]))
    for i in range(1, len(rows), 6):
        sheet([rows[0]] + rows[i:i + 6], a.tile, os.path.join(a.out, f"sheet_{i // 6 + 1}.jpg"))
    print("previews in", a.out)


if __name__ == "__main__":
    main()
